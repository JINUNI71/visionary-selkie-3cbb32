MISSING_IMAGES = []


def figure_img(alt, src, cap, page_slug, show_cap=True):
    rel = os.path.normpath(os.path.join(OUT_DIR, src))
    capt = cap or alt
    if os.path.exists(rel):
        body = '<img src="%s" alt="%s" loading="lazy">' % (attr(src), attr(alt))
        cls = "sw-figure"
    else:
        MISSING_IMAGES.append((page_slug, os.path.relpath(rel, ROOT)))
        body = ('<div class="sw-figure__ph" role="img" aria-label="%s">'
                '<span class="sw-figure__phlabel overline-sm">이미지 준비 중</span>'
                '<span class="sw-figure__phpath caption">%s</span></div>') % (
            attr(alt), esc(os.path.relpath(rel, ROOT)))
        cls = "sw-figure is-pending"
    fc = '<figcaption class="caption">%s</figcaption>' % inline(capt) if (show_cap and capt) else ""
    return '<figure class="%s">%s%s</figure>' % (cls, body, fc)


def figure_diagram(text, desc=None):
    d = '<span class="sw-figure__phdesc caption">%s</span>' % inline(desc) if desc else ""
    return ('<figure class="sw-figure is-pending is-diagram">'
            '<div class="sw-figure__ph"><span class="sw-figure__phlabel overline-sm">도식 준비 중</span>'
            '<span class="sw-figure__phtext">%s</span>%s</div></figure>') % (inline(text), d)


def figure_group(figs):
    if not figs:
        return ""
    cls = "sw-figs" + (" sw-figs--two" if len(figs) > 1 else "")
    return '<div class="%s">%s</div>' % (cls, "".join(figs))


