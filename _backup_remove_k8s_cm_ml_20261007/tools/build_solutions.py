# ── 인라인 서식 ───────────────────────────────────────────────
def esc(s):
    return html.escape(s, quote=False)


def attr(s):
    return html.escape(s, quote=True)


def inline(s):
    """md 한 줄을 HTML 로 — 이스케이프 후 **굵게** 만 살립니다."""
    s = esc(s.strip())
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    return s


