# ── md 읽기 ──────────────────────────────────────────────────
def read_md(path):
    raw = io.open(path, encoding="utf-8-sig").read().replace("\r\n", "\n")
    lines = [fix_text(l) for l in raw.split("\n")]
    doc = {"sections": []}
    cur = None
    for l in lines:
        m = re.match(r"^# CARD (\d+) — (.+)$", l)
        if m:
            doc["num"], doc["name"] = m.group(1), m.group(2).strip()
            continue
        m = re.match(r"^`([A-Z0-9 &·-]+)` · (.+)$", l)
        if m and cur is None:
            doc["cat_en"], doc["cat_ko"] = m.group(1), m.group(2)
            continue
        m = re.match(r"^## (\d+) (.+)$", l)
        if m:
            cur = {"num": m.group(1), "title": m.group(2).strip(), "lines": []}
            doc["sections"].append(cur)
            continue
        if cur is not None:
            if l.strip() == "---":
                continue
            cur["lines"].append(l)
    return doc


def blocks(lines):
    """섹션 본문을 블록 목록으로 나눕니다."""
    out = []
    i = 0
    n = len(lines)
    while i < n:
        l = lines[i]
        s = l.strip()
        if not s:
            i += 1
            continue
        if s.startswith("|"):
            rows = []
            while i < n and lines[i].strip().startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(re.match(r"^:?-{2,}:?$", c) for c in cells):
                    rows.append(cells)
                i += 1
            out.append(("table", rows))
            continue
        if s.startswith(">"):
            q = []
            while i < n and lines[i].strip().startswith(">"):
                q.append(re.sub(r"^>\s?", "", lines[i].strip()))
                i += 1
            out.append(("quote", q))
            continue
        if s.startswith("- "):
            items = []
            while i < n and lines[i].strip().startswith("- "):
                items.append(lines[i].strip()[2:])
                i += 1
            out.append(("list", items))
            continue
        if s.startswith("### "):
            out.append(("h3", s[4:]))
            i += 1
            continue
        m = re.match(r"^!\[(.*?)\]\((.+?)\)$", s)
        if m:
            cap = None
            if i + 1 < n and re.match(r"^\*[^*].*\*$", lines[i + 1].strip()):
                cap = lines[i + 1].strip()[1:-1]
                i += 1
            out.append(("img", (m.group(1), m.group(2), cap)))
            i += 1
            continue
        m = re.match(r"^\*도식 — (.+)\*$", s)
        if m:
            out.append(("diagram", m.group(1)))
            i += 1
            continue
        if re.match(r"^(`[^`]+`\s*)+$", s):
            out.append(("chips", re.findall(r"`([^`]+)`", s)))
            i += 1
            continue
        out.append(("p", s))
        i += 1
    return out


