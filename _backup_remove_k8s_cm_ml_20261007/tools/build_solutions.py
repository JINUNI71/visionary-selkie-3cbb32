def r_why(doc, cfg, sec):
    bl = blocks(sec["lines"])
    title = next(re.sub(r"\*\*", "", b[1]) for b in bl if b[0] == "p" and b[1].startswith("**"))
    rows = []
    cur = None
    for kind, v in bl:
        if kind == "h3":
            m = re.match(r"Why (\d+) — (.+)", v)
            cur = {"num": m.group(1), "name": m.group(2), "text": [], "notes": []}
            rows.append(cur)
        elif cur and kind == "p":
            cur["text"].append(v)
        elif cur and kind == "quote":
            cur["notes"].append(comment(v))
    out = []
    for r in rows:
        out.append("""        <div class="sw-row">
          <div>
            <div class="sw-row__label overline">%s</div>
            <h3 class="sw-row__name product-name">%s</h3>
          </div>
          <div class="sw-row__text body-row">%s</div>%s
        </div>""" % (r["num"], inline(r["name"]), "".join("<p>%s</p>" % inline(t) for t in r["text"]),
                     "".join("\n          " + n for n in r["notes"])))
    return section("why", "Why Softworks", title, '      <div class="sw-rows">\n%s\n      </div>' % "\n".join(out))


