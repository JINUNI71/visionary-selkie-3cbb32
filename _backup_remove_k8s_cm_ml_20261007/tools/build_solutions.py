def intro(eyebrow, title, text=None, hid=None):
    t = '<p class="sw-section-intro__text">%s</p>' % inline(text) if text else ""
    return ('<div class="sw-section-intro">\n'
            '        <span class="sw-eyebrow sw-eyebrow--light">%s</span>\n'
            '        <h2 class="sw-h2" id="%s">%s</h2>\n        %s\n      </div>') % (
        esc(eyebrow), hid, inline(title), t)


def section(sid, eyebrow, title, body, text=None):
    hid = sid + "-title"
    return ('\n  <section class="sw-section" id="%s" aria-labelledby="%s">\n'
            '    <div class="sw-container">\n      %s\n%s\n    </div>\n  </section>\n') % (
        sid, hid, intro(eyebrow, title, text, hid), body)


def comment(lines):
    t = " ".join(l for l in lines if l.strip()).replace("--", "—")
    return "<!-- %s -->" % t


def is_hidden_quote(q):
    t = " ".join(q)
    return "⚠️" in t or t.lstrip().startswith("메모")


def note_quote(q):
    t = " ".join(x for x in q if x.strip())
    t = re.sub(r"^출처\s*—\s*", "", t)
    return '<p class="sw-source caption"><span class="sw-source__label overline-sm">출처</span>%s</p>' % inline(t) \
        if " ".join(q).startswith("출처") else '<p class="sw-note caption">%s</p>' % inline(t)


# ── 표 → 화면 구성 ───────────────────────────────────────────
def numbers(rows):
    """수치 표(첫 열이 굵은 수치) → 숫자 격자."""
    head, body = rows[0], rows[1:]
    items = []
    for r in body:
        num = re.sub(r"\*\*(.+?)\*\*", r"\1", r[0])
        if len(r) == 2:
            items.append('<li><span class="sw-num__value">%s</span><span class="sw-num__text">%s</span></li>' % (
                esc(num), inline(r[1])))
        else:
            items.append('<li><span class="sw-num__value">%s</span><span class="sw-num__label">%s</span>'
                         '<span class="sw-num__text">%s</span></li>' % (esc(num), inline(r[1]), inline(r[2])))
    return '<ul class="sw-nums">%s</ul>' % "".join(items)


def pillars(rows):
    items = ['<li><span class="sw-pillar__name proof">%s</span><span class="sw-pillar__text">%s</span></li>' % (
        esc(re.sub(r"\*\*(.+?)\*\*", r"\1", r[0])), inline(r[1])) for r in rows[1:]]
    return '<ul class="sw-pillars">%s</ul>' % "".join(items)


def table(rows, lead_col=None, first_cls=None):
    head, body = rows[0], rows[1:]
    th = []
    for k, h in enumerate(head):
        c = "overline"
        if k == 0 and first_cls:
            c = first_cls + " overline"
        th.append('<th class="%s">%s</th>' % (c, esc(h)))
    trs = []
    for r in body:
        tds = []
        for k, c in enumerate(r):
            is_lead = (k == lead_col) or ("**" in c)
            cls = "is-lead body-row" if is_lead else "body-row"
            txt = re.sub(r"\*\*(.+?)\*\*", r"\1", c)
            tds.append('<td class="%s" data-label="%s">%s</td>' % (cls, attr(head[k]), inline(txt)))
        trs.append("<tr>%s</tr>" % "".join(tds))
    return ('<table class="sw-table">\n        <thead><tr>%s</tr></thead>\n        <tbody>\n          %s\n'
            '        </tbody>\n      </table>') % ("".join(th), "\n          ".join(trs))


def render_table(rows):
    head = rows[0]
    if head[0] == "수치":
        return numbers(rows)
    if head[0] == "지표":
        return numbers(rows)
    if head[0] == "Pillar":
        return pillars(rows)
    if head[0] == "구분" and len(head) == 3:
        return table(rows, lead_col=1, first_cls="col-step")
    return table(rows)


