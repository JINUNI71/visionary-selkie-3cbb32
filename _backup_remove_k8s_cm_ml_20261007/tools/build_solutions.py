def pick(title):
    t = title.lower()
    if t.startswith("hero"):
        return r_hero
    if t.startswith("why"):
        return r_why
    if t.startswith("scope"):
        return r_scope
    if t.startswith("knowledge"):
        return r_kb
    if t.startswith("field"):
        return r_issues
    if "제공 자료" in title:
        return r_vendor
    if "구성요소" in title or "핵심 기능" in title:
        return r_components
    if t.startswith("solution at a glance"):
        return r_glance
    if t.startswith("references"):
        return r_refs
    if t.startswith("operation"):
        return r_ops
    if t.startswith("related"):
        return r_related
    raise SystemExit("모르는 섹션: " + title)


