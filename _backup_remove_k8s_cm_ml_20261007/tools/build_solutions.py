def build(path):
    doc = read_md(path)
    cfg = dict(PAGES[doc["num"].zfill(2)])
    main = []
    related = ""
    for sec in doc["sections"]:
        fn = pick(sec["title"])
        if fn is r_related:
            related = fn(doc, cfg, sec)
            continue
        main.append(fn(doc, cfg, sec))
    main.append(related)
    main.append(r_cta(cfg))

    shell = io.open(SHELL_PAGE, encoding="utf-8").read()
    head, rest = shell.split('<main id="main">', 1)
    tail = rest.split("</main>", 1)[1]
    title = "%s · %s — SOFTWORKS" % (cfg["name"], cfg["cat"])
    head = re.sub(r"<title>.*?</title>", "<title>%s</title>" % esc(title), head, count=1)
    desc = re.sub(r"\s+", " ", cfg.get("lead", ""))[:150]
    head = re.sub(r'<meta name="description" content="[^"]*">', '<meta name="description" content="%s">' % attr(desc), head, count=1)
    head = head.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + MARK + "\n", 1)
    SHELL_NAME = os.path.basename(SHELL_PAGE)
    me = cfg["slug"] + ".html"
    head = head.replace('<a href="%s" aria-current="true">KR' % SHELL_NAME, '<a href="%s" aria-current="true">KR' % me)
    head = head.replace('<a href="%s" hreflang="en">' % SHELL_NAME, '<a href="%s" hreflang="en">' % me)
    page = head + '<main id="main">\n' + "".join(main) + "\n</main>" + tail
    page = re.sub(r"\n\s*\n\s*\n+", "\n\n", page)
    out = os.path.join(OUT_DIR, cfg["slug"] + ".html")
    io.open(out, "w", encoding="utf-8").write(page)
    return cfg["slug"]


