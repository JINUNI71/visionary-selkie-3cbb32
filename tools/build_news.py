def read_post(path):
    raw = io.open(path, encoding="utf-8-sig").read().replace("\r\n", "\n")
    meta, body = {}, raw
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n?(.*)$", raw, re.S)
    if m:
        body = m.group(2)
        for line in m.group(1).split("\n"):
            if not line.strip() or line.lstrip().startswith("#") or ":" not in line:
                continue
            k, v = line.split(":", 1)
            v = v.strip()
            if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
                v = v[1:-1]
            meta[k.strip().lower()] = v

    name = os.path.basename(path)[:-3]
    fm = re.match(r"^(\d{4}-\d{2}-\d{2})[-_ ]?(.*)$", name)
    date = meta.get("date") or (fm.group(1) if fm else "")
    date = date.replace(".", "-").replace("/", "-")
    if not re.match(r"^\d{4}-\d{2}-\d{2}$", date):
        raise ValueError("날짜가 없습니다. 파일 이름을 2026-09-29-제목.md 처럼 짓거나 date: 2026-09-29 를 넣으십시오.")

    title = meta.get("title", "")
    if not title:
        h = re.search(r"^\s{0,3}#\s+(.+?)\s*#*\s*$", body, re.M)
        if h:
            title = h.group(1)
            body = body[:h.start()] + body[h.end():]
    if not title:
        raise ValueError("제목이 없습니다. title: 을 넣거나 본문 첫 줄을 '# 제목' 으로 쓰십시오.")

    slug = meta.get("slug") or (fm.group(2) if fm else name)
    slug = re.sub(r"[^a-z0-9-]+", "-", slug.lower()).strip("-")
    if not slug:
        slug = date  # 한글 파일 이름이면 날짜로 주소를 만듭니다.

    cat = find_category(meta.get("category"))
    if cat is None:
        raise ValueError("분류가 없거나 잘못됐습니다. category: 에 %s 중 하나를 쓰십시오. (지금 값: '%s')"
                         % (" 또는 ".join(c["label"] for c in CATEGORIES), meta.get("category", "")))

    body_html = md_to_html(body)
    summary = meta.get("summary", "")
    if not summary:
        p = re.search(r"<p>(.*?)</p>", body_html, re.S)
        summary = plain(p.group(1)) if p else ""
        if len(summary) > 120:
            summary = summary[:118].rstrip() + "…"

    return {
        "file": os.path.relpath(path, ROOT),
        "title": title,
        "date": date,
        "slug": slug,
        "cat": cat,
        "summary": summary,
        "lead": meta.get("summary", ""),
        "cover": meta.get("cover", ""),
        "cover_alt": meta.get("cover_alt", ""),
        "link": meta.get("link", "").strip(),
        "link_label": meta.get("link_label", "").strip() or "원문 바로가기",
        "draft": meta.get("draft", "").lower() in ("true", "yes", "1", "y"),
        "body": body_html,
    }


