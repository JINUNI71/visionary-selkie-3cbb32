def dot(d):
    return d.replace("-", ".")


def list_file(cat, p):
    if cat is None:
        return "%s/index.html" % OUT_BASE if p == 1 else "%s/page-%d.html" % (OUT_BASE, p)
    return "%s/%s.html" % (OUT_BASE, cat["key"]) if p == 1 else "%s/%s-page-%d.html" % (OUT_BASE, cat["key"], p)


def post_file(post):
    """글이 놓인 전체 목록 페이지의 항목 주소 (main 에서 post["href"] 를 채웁니다)."""
    return post.get("href") or "%s#%s" % (list_file(None, 1), post["slug"])


def render_tabs(cat):
    items = [(None, "전체")] + [(c, c["label"]) for c in CATEGORIES]
    links = []
    for c, label in items:
        cur = (c is None and cat is None) or (c is not None and cat is not None and c["key"] == cat["key"])
        links.append('<a class="sw-tab%s" href="%s"%s>%s</a>' % (
            " is-active" if cur else "", list_file(c, 1), ' aria-current="page"' if cur else "", esc(label)))
    return '      <nav class="sw-tabs" aria-label="분류">\n        %s\n      </nav>\n' % "\n        ".join(links)


def news_row(post):
    return (
            '        <li>\n'
            '          <a class="sw-newsrow" href="%s">\n'
            '            <span class="sw-newsrow__meta">\n'
            '              <span class="sw-newsrow__cat overline">%s</span>\n'
            '              <time class="sw-newsrow__date overline" datetime="%s">%s</time>\n'
            '            </span>\n'
            '            <span class="sw-newsrow__body">\n'
            '              <span class="sw-newsrow__title product-name">%s</span>\n'
            '%s'
            '            </span>\n'
            '          </a>\n'
            '        </li>' % (
                post_file(post), esc(post["cat"]["label"]), post["date"], dot(post["date"]), esc(post["title"]),
                ('              <span class="sw-newsrow__text body-row">%s</span>\n' % esc(post["summary"]))
                if post["summary"] else ""))


def news_item(post, show_cat=True):
    """목록의 펼침형 항목 하나. <details> 를 써서 스크립트 없이도 열고 닫힙니다.
    접힌 상태: 분류 · 제목 · 작성일 · 펼침 표시(+/−)
    펼친 상태: 대표 이미지(cover) · 본문 · 원문 바로가기 버튼(link 가 있을 때만)"""
    pad = "              "
    cover = ""
    if post["cover"]:
        cover = '%s<figure class="sw-newsitem__cover"><img src="%s" alt="%s" loading="lazy"></figure>\n' % (
            pad, esc(post["cover"]), esc(post["cover_alt"]))
    action = ""
    if post["link"]:
        action = ('%s<div class="sw-newsitem__actions">\n'
                  '%s  <a class="sw-btn sw-btn--line" href="%s" target="_blank" rel="noopener">%s →'
                  '<span class="sw-sr"> (새 창에서 열림)</span></a>\n'
                  '%s</div>\n') % (pad, pad, esc(post["link"]), esc(post["link_label"]), pad)
    body = "\n".join(pad + "  " + l if l.strip() else l for l in post["body"].split("\n"))
    return (
        '        <li class="sw-newsitem">\n'
        '          <details class="sw-newsitem__details" id="%s">\n'
        '            <summary class="sw-newsitem__bar">\n'
        '%s'
        '              <span class="sw-newsitem__title">%s</span>\n'
        '              <time class="sw-newsitem__date" datetime="%s">%s</time>\n'
        '              <span class="sw-newsitem__mark" aria-hidden="true"></span>\n'
        '            </summary>\n'
        '            <div class="sw-newsitem__panel">\n'
        '%s'
        '%s<div class="sw-prose sw-newsitem__body">\n%s\n%s</div>\n'
        '%s'
        '            </div>\n'
        '          </details>\n'
        '        </li>') % (
            esc(post["slug"]),
            ('              <span class="sw-newsitem__cat overline">%s</span>\n' % esc(post["cat"]["label"])) if show_cat else "",
            esc(post["title"]), post["date"], dot(post["date"]),
            cover, pad, body, pad, action)


def crumbs(items, ind="      "):
    """브레드크럼 — items 는 (글자, 주소 또는 None) 목록이고 마지막이 현재 페이지입니다."""
    out = [ind + '<nav class="sw-crumbs" aria-label="현재 위치">', ind + '  <ol class="sw-crumbs__list">']
    for i, (label, href) in enumerate(items):
        if i == len(items) - 1:
            inner = '<span aria-current="page">%s</span>' % esc(label)
        elif href:
            inner = '<a href="%s">%s</a>' % (href, esc(label))
        else:
            inner = esc(label)
        out.append(ind + '    <li class="sw-crumbs__item">%s</li>' % inner)
    out += [ind + "  </ol>", ind + "</nav>"]
    return "\n".join(out)


def render_crumbs(cat):
    # 주소는 사이트 루트 기준으로 쓰고, page() 의 relativize 가 이 페이지 위치에 맞게 바꿉니다.
    items = [("홈", "index.html"), ("회사소개", "company/index.html")]
    if cat is None:
        items.append((LIST_TITLE, None))
    else:
        items += [(LIST_TITLE, list_file(None, 1)), (cat["label"], None)]
    return crumbs(items)


def render_list(posts, cat, p, pages):
    # 연도별로 묶어 최신 연도·최신 날짜 순으로 보여 줍니다 (posts 는 이미 최신순).
    groups = []
    for post in posts:
        y = post["date"][:4]
        if not groups or groups[-1][0] != y:
            groups.append((y, []))
        groups[-1][1].append(news_item(post, show_cat=cat is None))
    if groups:
        # 연도 탭 — site.js 가 hidden 을 풀고 고른 연도만 보이게 합니다.
        #   스크립트가 없으면 탭은 숨은 채로, 아래 연도 묶음이 모두 제목과 함께 보입니다.
        tabs = []
        for k, (y, rows) in enumerate(groups):
            tabs.append('<button type="button" class="sw-yeartab" role="tab" id="yeartab-%s" aria-controls="year-%s" '
                        'aria-selected="%s"%s>%s</button>'
                        % (y, y, "true" if k == 0 else "false", "" if k == 0 else ' tabindex="-1"', y))
        parts = []
        for y, rows in groups:
            parts.append(
                '      <section class="sw-newsyear" id="year-%s" aria-labelledby="year-%s-title">\n'
                '        <h2 class="sw-newsyear__title" id="year-%s-title">%s</h2>\n'
                '        <ol class="sw-newsacc%s">\n%s\n        </ol>\n'
                '      </section>' % (y, y, y, y, "" if cat is None else " sw-newsacc--nocat", "\n".join(rows)))
        listing = ('      <div class="sw-yeartabs" role="tablist" aria-label="연도" hidden>\n        %s\n      </div>\n'
                   '      <div class="sw-newsyears">\n%s\n      </div>') % ("\n        ".join(tabs), "\n".join(parts))
    else:
        listing = '      <p class="sw-newslist-empty">아직 올라온 글이 없습니다.</p>'

    pager = ""
    if pages > 1:
        items = []
        if p > 1:
            items.append('<a class="sw-pager__link" href="%s" rel="prev">이전</a>' % list_file(cat, p - 1))
        for k in range(1, pages + 1):
            if k == p:
                items.append('<a class="sw-pager__link is-current" href="%s" aria-current="page">%d</a>' % (list_file(cat, k), k))
            else:
                items.append('<a class="sw-pager__link" href="%s">%d</a>' % (list_file(cat, k), k))
        if p < pages:
            items.append('<a class="sw-pager__link" href="%s" rel="next">다음 →</a>' % list_file(cat, p + 1))
        pager = '\n      <nav class="sw-pager" aria-label="목록 페이지">\n        %s\n      </nav>' % "\n        ".join(items)

    return """<main id="main">
  <!-- Hero — 다른 하위 페이지와 같은 상세 히어로 (선화: assets/img/hero/news.svg) -->
  <section class="sw-hero sw-hero--detail" data-hero="news" aria-labelledby="page-title">
    <div class="sw-hero__inner">
%s
      <span class="sw-eyebrow sw-eyebrow--dark">%s</span>
      <h1 class="sw-hero__title" id="page-title">%s</h1>
      <p class="sw-hero__lead">%s</p>
    </div>
  </section>
  <!-- 목록 — 분류 탭 · 연도별 펼침형 목록 -->
  <section class="sw-page sw-page--news" aria-label="%s 목록">
    <div class="sw-container">
%s%s%s
    </div>
  </section>
%s</main>""" % (render_crumbs(cat), LIST_EYEBROW, HERO_TITLE, HERO_LEAD,
                 esc(LIST_TITLE if cat is None else cat["label"]), render_tabs(cat), listing, pager, CTA)


LATEST_START = "<!-- LATEST_NEWS:START"
LATEST_END = "<!-- LATEST_NEWS:END -->"
LATEST_COUNT = 3


def fill_latest(posts):
    """company/index.html 의 LATEST_NEWS 표시 사이를 최신 글로 채웁니다."""
    s = io.open(SHELL_PAGE, encoding="utf-8").read()
    if LATEST_START not in s or LATEST_END not in s:
        return
    a = s.index("\n", s.index(LATEST_START)) + 1
    b = s.index(LATEST_END)
    rows = [news_row(q) for q in posts[:LATEST_COUNT]]
    if rows:
        block = '      <ol class="sw-newslist">\n%s\n      </ol>\n' % "\n".join(rows)
    else:
        block = '      <p class="sw-newslist-empty">아직 올라온 글이 없습니다.</p>\n'
    io.open(SHELL_PAGE, "w", encoding="utf-8").write(s[:a] + relativize(block, SHELL_REL) + s[b:])



def main():
    if not os.path.isdir(SRC_DIR):
        print("  md/news/ 폴더가 없어 건너뜁니다.")
        return 0
    posts, errors = [], []
    for path in sorted(glob.glob(os.path.join(SRC_DIR, "*.md"))):
        base = os.path.basename(path)
        if base.startswith(("_", ".")) or base.lower() == "readme.md":
            continue
        try:
            post = read_post(path)
        except ValueError as e:
            errors.append("%s — %s" % (base, e))
            continue
        if not post["draft"]:
            posts.append(post)

    reserved = set(c["key"] for c in CATEGORIES) | {"index"}
    seen = {}
    for post in posts:
        if post["slug"] in seen:
            post["slug"] = "%s-%s" % (post["date"], post["slug"]) if not post["slug"].startswith(post["date"]) else post["slug"] + "-2"
        s = post["slug"]
        if s in seen or s in reserved or s.startswith("page-") or any(s.startswith(k + "-page-") for k in reserved):
            errors.append("%s — 주소(slug) '%s' 는 쓸 수 없습니다(겹치거나 목록 주소와 같음). slug: 를 따로 지정하십시오." % (post["file"], s))
        seen[s] = post
        if post["link"] and not post["link"].startswith(("http://", "https://")):
            errors.append("%s — link: 는 http:// 또는 https:// 로 시작하는 원문 주소여야 합니다: %s" % (post["file"], post["link"]))
        if post["cover"] and not post["cover"].startswith(("http://", "https://")) \
                and not os.path.exists(os.path.join(ROOT, post["cover"])):
            errors.append("%s — cover 이미지를 찾지 못했습니다: %s" % (post["file"], post["cover"]))

    if errors:
        for e in errors:
            print("  ! " + e)
        return 1

    posts.sort(key=lambda p: (p["date"], p["file"]), reverse=True)
    for k, post in enumerate(posts):
        post["href"] = "%s#%s" % (list_file(None, k // PER_PAGE + 1), post["slug"])

    # 지난번에 만든 파일을 지웁니다 (GENERATED 표시가 있는 것만).
    #   예전 구조(루트의 news*.html, news/)로 만든 파일도 함께 정리합니다.
    olds = (glob.glob(os.path.join(ROOT, "news*.html")) + glob.glob(os.path.join(ROOT, "news", "*.html"))
            + glob.glob(os.path.join(OUT_DIR, "*.html")))
    for old in olds:
        with io.open(old, encoding="utf-8") as f:
            if "GENERATED by tools/build_news.py" in f.read(400):
                os.remove(old)
    if not os.path.isdir(OUT_DIR):
        os.makedirs(OUT_DIR)

    shell = load_shell()
    counts = []
    for cat in [None] + CATEGORIES:
        subset = posts if cat is None else [q for q in posts if q["cat"]["key"] == cat["key"]]
        pages = max(1, (len(subset) + PER_PAGE - 1) // PER_PAGE)
        name = LIST_TITLE if cat is None else "%s — %s" % (cat["label"], LIST_TITLE)
        for p in range(1, pages + 1):
            chunk = subset[(p - 1) * PER_PAGE:p * PER_PAGE]
            title = "%s — SOFTWORKS" % name if p == 1 else "%s (%d쪽) — SOFTWORKS" % (name, p)
            fn = list_file(cat, p)
            io.open(os.path.join(ROOT, fn), "w", encoding="utf-8").write(
                page(shell, fn, title, plain(LIST_INTRO), render_list(chunk, cat, p, pages)))
        if cat is not None:
            counts.append("%s %d" % (cat["label"], len(subset)))

    fill_latest(posts)
    print("  글 %d개 (%s) → 펼침형 목록 전체·분류별" % (len(posts), ", ".join(counts)))
    return 0


