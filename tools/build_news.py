def load_shell():
    s = io.open(SHELL_PAGE, encoding="utf-8").read()
    s = rootify(s, SHELL_REL)
    a, b = s.index('<main id="main">'), s.index("</main>") + len("</main>")
    head, tail = s[:a], s[b:]
    # 회사소개 메뉴는 강조로 두되, 이 페이지 자체가 회사소개는 아니므로 aria-current 는 뺍니다.
    head = head.replace('aria-current="page" data-menu="company"', 'data-menu="company"')
    return head, tail


def page(shell, filename, title, desc, main, extra_meta=""):
    head, tail = shell
    h = re.sub(r"<title>.*?</title>", "<title>%s</title>" % esc(title), head, count=1, flags=re.S)
    h = re.sub(r'<meta name="description" content="[^"]*">',
               '<meta name="description" content="%s">%s' % (esc(desc), extra_meta), h, count=1)
    h = h.replace('href="%s" aria-current="true">KR' % SHELL_REL, 'href="%s" aria-current="true">KR' % filename)
    h = h.replace('href="%s" hreflang="en"' % SHELL_REL, 'href="%s" hreflang="en"' % filename)
    h = h.replace("<!DOCTYPE html>", "<!DOCTYPE html>\n" + MARK, 1)
    return relativize(h + main + tail, filename)


def rootify(doc, page_path):
    """relativize 의 반대 — page_path 기준 상대 링크를 사이트 루트 기준으로 되돌립니다.
    헤더·푸터를 company/index.html 에서 가져오므로, 다른 위치의 페이지에 붙이기 전에 씁니다."""
    here = os.path.dirname(page_path)

    def fix(m):
        attr, url = m.group(1), m.group(2)
        if url.startswith(("http:", "https:", "#", "mailto:", "tel:", "data:", "/")):
            return m.group(0)
        path, frag = (url.split("#", 1) + [""])[:2]
        if not path:
            return m.group(0)
        root = os.path.normpath(os.path.join(here, path)).replace(os.sep, "/")
        return '%s="%s%s"' % (attr, root, "#" + frag if frag else "")

    return re.sub(r'\b(href|src)="([^"]+)"', fix, doc)


def relativize(doc, page_path):
    """루트 기준 링크(assets/…, news/…, products/…)를 이 페이지 위치 기준 상대 경로로 바꿉니다."""
    here = os.path.dirname(page_path) or "."

    def fix(m):
        attr, url = m.group(1), m.group(2)
        if url.startswith(("http:", "https:", "#", "mailto:", "tel:", "data:", "/", "../")):
            return m.group(0)
        path, frag = (url.split("#", 1) + [""])[:2]
        if not path:
            return m.group(0)
        rel = os.path.relpath(path, here).replace(os.sep, "/")
        return '%s="%s%s"' % (attr, rel, "#" + frag if frag else "")

    return re.sub(r'\b(href|src)="([^"]+)"', fix, doc)


