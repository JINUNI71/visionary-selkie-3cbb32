RE_FENCE = re.compile(r"^\s{0,3}(`{3,}|~{3,})\s*([\w+#.-]*)\s*$")
RE_HEAD = re.compile(r"^\s{0,3}(#{1,6})\s+(.*?)\s*#*\s*$")
RE_HR = re.compile(r"^\s{0,3}([-*_])(\s*\1){2,}\s*$")
RE_QUOTE = re.compile(r"^\s{0,3}>\s?(.*)$")
RE_LIST = re.compile(r"^(\s*)([-*+]|\d{1,9}[.)])\s+(.*)$")
RE_TSEP = re.compile(r"^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$")
RE_HTML = re.compile(r"^\s{0,3}<(/?)([a-zA-Z][\w-]*)[\s>/]")


def inline(text):
    codes = []

    def keep_code(m):
        codes.append("<code>%s</code>" % html.escape(m.group(2), quote=False))
        return "\x00%d\x00" % (len(codes) - 1)

    t = re.sub(r"(`+)(.+?)\1", keep_code, text)
    # 태그처럼 생긴 것(<br>, <span …>)은 그대로 두고, 나머지 <, > 와 & 는 바꿉니다.
    t = re.sub(r"&(?!#?\w+;)", "&amp;", t)
    t = re.sub(r"<(?![a-zA-Z/!])", "&lt;", t)

    def img(m):
        alt, src, title = m.group(1), m.group(2), m.group(3)
        attrs = ' src="%s" alt="%s" loading="lazy"' % (esc(src), esc(alt))
        if title:
            attrs += ' title="%s"' % esc(title)
        return "<img%s>" % attrs

    t = re.sub(r'!\[([^\]]*)\]\(\s*<?([^)\s>]+)>?(?:\s+"([^"]*)")?\s*\)', img, t)

    def link(m):
        label, href = m.group(1), m.group(2)
        extra = ""
        if href.startswith(("http://", "https://")):
            extra = ' target="_blank" rel="noopener"'
        return '<a href="%s"%s>%s</a>' % (esc(href), extra, label)

    t = re.sub(r'\[([^\]]+)\]\(\s*<?([^)\s>]+)>?(?:\s+"[^"]*")?\s*\)', link, t)
    t = re.sub(r"<(https?://[^>\s]+)>",
               lambda m: '<a href="%s" target="_blank" rel="noopener">%s</a>' % (m.group(1), m.group(1)), t)
    t = re.sub(r"\*\*(?=\S)(.+?)(?<=\S)\*\*", r"<strong>\1</strong>", t)
    t = re.sub(r"(?<![\w])__(?=\S)(.+?)(?<=\S)__(?![\w])", r"<strong>\1</strong>", t)
    t = re.sub(r"(?<![*\w])\*(?=[^\s*])(.+?)(?<=[^\s*])\*(?![*\w])", r"<em>\1</em>", t)
    t = re.sub(r"~~(?=\S)(.+?)(?<=\S)~~", r"<del>\1</del>", t)
    t = re.sub(r"(?:  +|\\)\n", "<br>\n", t)
    t = re.sub(r"\x00(\d+)\x00", lambda m: codes[int(m.group(1))], t)
    return t


def is_block_start(line, nxt=None):
    return bool(RE_FENCE.match(line) or RE_HEAD.match(line) or RE_HR.match(line)
                or RE_QUOTE.match(line) or RE_LIST.match(line) or RE_HTML.match(line)
                or ("|" in line and nxt is not None and RE_TSEP.match(nxt)))


def indent_of(s):
    return len(s) - len(s.lstrip(" "))


def split_row(line):
    s = line.strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|"):
        s = s[:-1]
    return [c.strip() for c in re.split(r"(?<!\\)\|", s)]


def md_to_html(text):
    lines = text.replace("\r\n", "\n").replace("\t", "    ").split("\n")
    out = []
    i, n = 0, len(lines)
    while i < n:
        line = lines[i]
        nxt = lines[i + 1] if i + 1 < n else None
        if not line.strip():
            i += 1
            continue

        m = RE_FENCE.match(line)
        if m:
            fence, lang = m.group(1), m.group(2)
            buf = []
            i += 1
            while i < n and not lines[i].strip().startswith(fence[0] * len(fence)):
                buf.append(lines[i])
                i += 1
            i += 1
            cls = ' class="language-%s"' % esc(lang) if lang else ""
            out.append("<pre><code%s>%s</code></pre>" % (cls, html.escape("\n".join(buf), quote=False)))
            continue

        m = RE_HEAD.match(line)
        if m:
            # 페이지 제목이 h1 이므로 본문의 # 과 ## 는 모두 h2 로 씁니다.
            level = min(max(len(m.group(1)), 2), 6)
            out.append("<h%d>%s</h%d>" % (level, inline(m.group(2)), level))
            i += 1
            continue

        if RE_HR.match(line):
            out.append("<hr>")
            i += 1
            continue

        if RE_QUOTE.match(line):
            buf = []
            while i < n and lines[i].strip() and (RE_QUOTE.match(lines[i]) or buf):
                q = RE_QUOTE.match(lines[i])
                buf.append(q.group(1) if q else lines[i])
                i += 1
            out.append("<blockquote>\n%s\n</blockquote>" % md_to_html("\n".join(buf)))
            continue

        if "|" in line and nxt is not None and RE_TSEP.match(nxt):
            head = split_row(line)
            aligns = []
            for c in split_row(nxt):
                a = ""
                if c.startswith(":") and c.endswith(":"):
                    a = "center"
                elif c.endswith(":"):
                    a = "right"
                aligns.append(a)
            i += 2
            rows = []
            while i < n and lines[i].strip() and "|" in lines[i]:
                rows.append(split_row(lines[i]))
                i += 1

            def cell(tag, c, k):
                a = aligns[k] if k < len(aligns) and aligns[k] else ""
                st = ' style="text-align:%s"' % a if a else ""
                return "<%s%s>%s</%s>" % (tag, st, inline(c.replace("\\|", "|")), tag)

            t = ['<div class="sw-prose__table"><table>', "<thead><tr>"]
            t += [cell("th", c, k) for k, c in enumerate(head)]
            t.append("</tr></thead><tbody>")
            for r in rows:
                r = (r + [""] * len(head))[:len(head)]
                t.append("<tr>" + "".join(cell("td", c, k) for k, c in enumerate(r)) + "</tr>")
            t.append("</tbody></table></div>")
            out.append("".join(t))
            continue

        m = RE_LIST.match(line)
        if m:
            html_list, i = parse_list(lines, i)
            out.append(html_list)
            continue

        if RE_HTML.match(line):
            buf = []
            while i < n and lines[i].strip():
                buf.append(lines[i])
                i += 1
            out.append("\n".join(buf))
            continue

        buf = [line]
        i += 1
        while i < n and lines[i].strip() and not is_block_start(lines[i], lines[i + 1] if i + 1 < n else None):
            buf.append(lines[i])
            i += 1
        # 끝 공백 2칸 줄바꿈을 살리려고 오른쪽 공백은 inline 뒤에 정리합니다.
        para = "\n".join(buf).strip()
        para = re.sub(r"\n[ ]{0,3}", "\n", para)
        body = inline(para).rstrip()
        only_img = re.match(r'^<img [^>]*?(?: title="([^"]*)")?>$', body)
        if only_img:
            cap = only_img.group(1)
            fig = body.replace(' title="%s"' % cap, "") if cap else body
            out.append("<figure>%s%s</figure>" % (fig, "<figcaption>%s</figcaption>" % cap if cap else ""))
        else:
            out.append("<p>%s</p>" % body)
    return "\n".join(out)


def parse_list(lines, i):
    n = len(lines)
    first = RE_LIST.match(lines[i])
    base = len(first.group(1))
    ordered = first.group(2)[0].isdigit()
    start = int(first.group(2)[:-1]) if ordered else 1
    items = []  # [lines, loose?, offset]
    loose = False
    while i < n:
        line = lines[i]
        m = RE_LIST.match(line)
        if m and len(m.group(1)) == base and m.group(2)[0].isdigit() == ordered:
            offset = len(line) - len(m.group(3))
            items.append([[m.group(3)], offset])
            i += 1
            continue
        if not line.strip():
            j = i + 1
            while j < n and not lines[j].strip():
                j += 1
            if j < n and items and (indent_of(lines[j]) > base or (
                    RE_LIST.match(lines[j]) and len(RE_LIST.match(lines[j]).group(1)) == base
                    and RE_LIST.match(lines[j]).group(2)[0].isdigit() == ordered)):
                if indent_of(lines[j]) > base:
                    items[-1][0].append("")
                loose = True
                i = j
                continue
            break
        if items and indent_of(line) > base:
            off = items[-1][1]
            strip = min(indent_of(line), off)
            items[-1][0].append(line[strip:])
            i += 1
            continue
        if items and not m and not is_block_start(line):
            items[-1][0].append(line.strip())  # 들여쓰지 않고 이어 쓴 줄
            i += 1
            continue
        break
    tag = "ol" if ordered else "ul"
    attr = ' start="%d"' % start if ordered and start != 1 else ""
    parts = ["<%s%s>" % (tag, attr)]
    for body, _ in items:
        inner = md_to_html("\n".join(body))
        if not loose:
            inner = re.sub(r"^<p>(.*?)</p>", r"\1", inner, count=1, flags=re.S)
        parts.append("<li>%s</li>" % inner)
    parts.append("</%s>" % tag)
    return "\n".join(parts), i


def plain(s):
    s = re.sub(r"<[^>]+>", "", s)
    return html.unescape(re.sub(r"\s+", " ", s)).strip()


